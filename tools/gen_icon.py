"""Generates the brick-wall icon vectors. Run from the project root: python -I tools/gen_icon.py

Four rows of rounded bricks, offset every other row, sized so the wall's corners stay inside the
adaptive-icon safe zone (a 33-unit radius circle in the 108-unit canvas).
"""

W, H, G, R = 48.0, 8.8, 3.2, 1.8  # wall width, brick height, mortar gap, corner radius
ROWS = 4

full = (W - G) / 2
half = (W - 2 * G - full) / 2
total_h = ROWS * H + (ROWS - 1) * G
X0 = (108 - W) / 2
Y0 = (108 - total_h) / 2


def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def rect(x, y, w, h, r):
    return (f"M{f(x + r)},{f(y)}h{f(w - 2 * r)}a{f(r)},{f(r)} 0,0 1,{f(r)},{f(r)}v{f(h - 2 * r)}"
            f"a{f(r)},{f(r)} 0,0 1,{f(-r)},{f(r)}h{f(-(w - 2 * r))}a{f(r)},{f(r)} 0,0 1,{f(-r)},{f(-r)}"
            f"v{f(-(h - 2 * r))}a{f(r)},{f(r)} 0,0 1,{f(r)},{f(-r)}z")


parts = []
y = Y0
for i in range(ROWS):
    x = X0
    for w in ([full, full] if i % 2 == 0 else [half, full, half]):
        parts.append(rect(x, y, w, H, R))
        x += w + G
    y += H + G
PATH = " ".join(parts)


def vec(name, size, vp, tx, ty, color, comment):
    with open(f"res/drawable/{name}.xml", "w") as out:
        out.write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by tools/gen_icon.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}" android:height="{size}"
    android:viewportWidth="{f(vp)}" android:viewportHeight="{f(vp)}">
    <group android:translateX="{f(tx)}" android:translateY="{f(ty)}">
        <path android:fillColor="{color}" android:pathData="{PATH}" />
    </group>
</vector>
''')


vec("ic_launcher_foreground", "108dp", 108, 0, 0, "#FF000000",
    "Brick wall (launcher), black on the white background layer.")
vec("ic_launcher_monochrome", "108dp", 108, 0, 0, "#FFFFFFFF",
    "Brick wall for themed icons; the launcher tints it.")
# In-app copy: crop the 108 canvas to a square just around the wall.
vp = W + 2
vec("ic_wall", "40dp", vp, -(X0 - 1), -(Y0 - (vp - total_h) / 2), "@color/fw_on_primary_container",
    "Brick wall shown on the summary card.")

corner = ((W / 2) ** 2 + (total_h / 2) ** 2) ** 0.5
print(f"wall {f(W)}x{f(total_h)} at ({f(X0)},{f(Y0)}), corner radius from center {corner:.1f} (safe <= 33)")
